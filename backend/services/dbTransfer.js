/* Admin > DB Transfer: copies a Neon (PostgreSQL) database into another one.
   Same logic as neon-schema.js and neon-merge.js in the project folder, run from the admin panel.
   Existing rows in the destination are NEVER changed or deleted (inserts use ON CONFLICT DO NOTHING).
   The two connection strings are used only while a job runs: they are not saved, not logged (only the host name is shown). */
const { Client } = require("pg");

const q = (s) => '"' + String(s).replace(/"/g, '""') + '"';
const lit = (s) => "'" + String(s).replace(/'/g, "''") + "'";

let job = null;            /* the current / last job (one at a time) */
const MAX_LOG = 3000;

function cleanUrl(v) {
  const s = String(v || "").trim();
  if (!/^postgres(ql)?:\/\//i.test(s)) throw new Error("A connection string must start with postgresql://");
  let u; try { u = new URL(s); } catch (e) { throw new Error("That connection string is not a valid URL."); }
  if (!u.hostname) throw new Error("The connection string has no host name.");
  return s;
}
const hostOf = (s) => { try { return new URL(s).host; } catch (e) { return "?"; } };
/* never let a password reach the screen or the server log */
const scrub = (msg, urls) => { let m = String(msg || ""); for (const u of urls) { try { const p = decodeURIComponent(new URL(u).password); if (p) m = m.split(p).join("****"); } catch (e) {} m = m.split(u).join("<url>"); } return m; };

function envUrls() {
  const s = String(process.env.SRC_URL || "").trim(), d = String(process.env.DST_URL || "").trim();
  return { src: s ? hostOf(s) : "", dst: d ? hostOf(d) : "" };
}

/* ---------- schema (neon-schema.js) ---------- */
async function schemaStep(s, d, post, log) {
  let ok = 0, warn = 0;
  const run = async (sql) => {
    try { await d.query(sql); ok++; }
    catch (e) {
      if (/already exists|multiple primary keys/i.test(e.message)) return;
      warn++; log("WARN: " + e.message + " | " + sql.slice(0, 140));
    }
  };
  if (!post) {
    for (const r of (await s.query(`select extname::text e from pg_extension where extname <> 'plpgsql'`)).rows)
      await run(`create extension if not exists ${q(r.e)}`);
    const enums = await s.query(
      `select t.typname::text n, array_agg(e.enumlabel::text order by e.enumsortorder) labels
       from pg_type t join pg_enum e on e.enumtypid = t.oid
       join pg_namespace n on n.oid = t.typnamespace where n.nspname = 'public' group by t.typname`);
    for (const r of enums.rows) await run(`create type public.${q(r.n)} as enum (${r.labels.map(lit).join(", ")})`);
    const seqs = await s.query(
      `select c.relname::text n, format_type(q.seqtypid, null) typ, q.seqstart st, q.seqincrement inc,
              q.seqmin mn, q.seqmax mx, q.seqcache ca, q.seqcycle cy
       from pg_sequence q join pg_class c on c.oid = q.seqrelid
       join pg_namespace n on n.oid = c.relnamespace
       where n.nspname = 'public'
         and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')`);
    for (const r of seqs.rows)
      await run(`create sequence if not exists public.${q(r.n)} as ${r.typ} increment by ${r.inc} minvalue ${r.mn} maxvalue ${r.mx} start ${r.st} cache ${r.ca} ${r.cy ? "cycle" : "no cycle"}`);
    const cols = await s.query(
      `select c.relname::text t, a.attname::text col, format_type(a.atttypid, a.atttypmod) typ,
              a.attnotnull nn, a.attidentity::text ident, a.attgenerated::text gen,
              pg_get_expr(ad.adbin, ad.adrelid) def
       from pg_attribute a join pg_class c on c.oid = a.attrelid
       join pg_namespace n on n.oid = c.relnamespace
       left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
       where n.nspname = 'public' and c.relkind = 'r' and a.attnum > 0 and not a.attisdropped
       order by c.relname, a.attnum`);
    const byTable = new Map();
    for (const r of cols.rows) { if (!byTable.has(r.t)) byTable.set(r.t, []); byTable.get(r.t).push(r); }
    for (const [t, cs] of byTable) {
      const defs = cs.map((c) => {
        let x = `${q(c.col)} ${c.typ}`;
        if (c.ident === "a") x += " generated always as identity";
        else if (c.ident === "d") x += " generated by default as identity";
        else if (c.gen === "s") x += ` generated always as (${c.def}) stored`;
        else if (c.def) x += ` default ${c.def}`;
        if (c.nn && !c.ident) x += " not null";
        return x;
      });
      await run(`create table if not exists public.${q(t)} (${defs.join(", ")})`);
      log("table " + t);
    }
    const cons = await s.query(
      `select k.conname::text name, r.relname::text t, pg_get_constraintdef(k.oid) def
       from pg_constraint k join pg_class r on r.oid = k.conrelid
       join pg_namespace n on n.oid = r.relnamespace
       where n.nspname = 'public' and k.contype in ('p','u','c','x') order by r.relname`);
    for (const r of cons.rows) await run(`alter table public.${q(r.t)} add constraint ${q(r.name)} ${r.def}`);
    const own = await s.query(
      `select sq.relname::text seq, t.relname::text tbl, a.attname::text col
       from pg_depend d join pg_class sq on sq.oid = d.objid and sq.relkind = 'S'
       join pg_class t on t.oid = d.refobjid
       join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid
       join pg_namespace n on n.oid = sq.relnamespace
       where d.deptype = 'a' and n.nspname = 'public'`);
    for (const r of own.rows) await run(`alter sequence public.${q(r.seq)} owned by public.${q(r.tbl)}.${q(r.col)}`);
  } else {
    const fks = await s.query(
      `select k.conname::text name, r.relname::text t, pg_get_constraintdef(k.oid) def
       from pg_constraint k join pg_class r on r.oid = k.conrelid
       join pg_namespace n on n.oid = r.relnamespace
       where n.nspname = 'public' and k.contype = 'f' order by r.relname`);
    for (const r of fks.rows) await run(`alter table public.${q(r.t)} add constraint ${q(r.name)} ${r.def}`);
    const idx = await s.query(
      `select pg_get_indexdef(i.indexrelid) def
       from pg_index i join pg_class c on c.oid = i.indrelid
       join pg_namespace n on n.oid = c.relnamespace
       where n.nspname = 'public' and c.relkind = 'r'
         and not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid)`);
    for (const r of idx.rows) await run(r.def.replace(/^CREATE (UNIQUE )?INDEX /i, "CREATE $1INDEX IF NOT EXISTS "));
  }
  log(`Done. ${ok} statements applied, ${warn} warnings.`);
  return { ok, warn };
}

/* ---------- rows (neon-merge.js) ---------- */
async function tablesOf(c) {
  return (await c.query(`select table_name from information_schema.tables where table_schema='public' and table_type='BASE TABLE' order by 1`)).rows.map((x) => x.table_name);
}
async function columnsOf(c, t) {
  return (await c.query(`select column_name, data_type, is_generated, identity_generation from information_schema.columns where table_schema='public' and table_name=$1 order by ordinal_position`, [t])).rows;
}
async function fkOrder(c, names) {
  const r = await c.query(
    `select cl.relname as child, pl.relname as parent
     from pg_constraint k join pg_class cl on cl.oid = k.conrelid join pg_class pl on pl.oid = k.confrelid
     join pg_namespace n on n.oid = cl.relnamespace
     where k.contype='f' and n.nspname='public' and cl.relname <> pl.relname`);
  const deps = new Map(names.map((n) => [n, new Set()]));
  for (const { child, parent } of r.rows) if (deps.has(child) && deps.has(parent)) deps.get(child).add(parent);
  const out = [], done = new Set();
  while (out.length < names.length) {
    let progressed = false;
    for (const n of names) {
      if (done.has(n)) continue;
      if ([...deps.get(n)].every((p) => done.has(p))) { out.push(n); done.add(n); progressed = true; }
    }
    if (!progressed) for (const n of names) if (!done.has(n)) { out.push(n); done.add(n); }
  }
  return out;
}
async function rowsStep(src, dst, apply, log, isCancelled) {
  log(apply ? "MODE: APPLY (writing to destination)" : "MODE: DRY RUN (no writes)");
  const srcTables = await tablesOf(src);
  const dstTables = new Set(await tablesOf(dst));
  const order = await fkOrder(src, srcTables);
  let totalInserted = 0;
  for (const t of order) {
    if (isCancelled()) throw new Error("Stopped.");
    if (!dstTables.has(t)) { log(`SKIP  ${t}: table does not exist in destination (run "1. Copy structure" first)`); continue; }
    const sCols = await columnsOf(src, t), dCols = await columnsOf(dst, t);
    const dMap = new Map(dCols.map((c) => [c.column_name, c]));
    const cols = sCols.filter((c) => { const d = dMap.get(c.column_name); return d && d.is_generated !== "ALWAYS"; });
    if (!cols.length) { log(`SKIP  ${t}: no common columns`); continue; }
    const total = Number((await src.query(`select count(*) from ${q(t)}`)).rows[0].count);
    const before = Number((await dst.query(`select count(*) from ${q(t)}`)).rows[0].count);
    if (!apply) { log(`${t}: source ${total} rows, destination ${before} rows`); continue; }
    if (!total) { log(`${t}: empty, nothing to copy`); continue; }
    const names = cols.map((c) => q(c.column_name)).join(", ");
    const isJson = cols.map((c) => c.data_type === "json" || c.data_type === "jsonb");
    const hasIdentityAlways = cols.some((c) => dMap.get(c.column_name).identity_generation === "ALWAYS");
    const batch = Math.max(1, Math.min(500, Math.floor(60000 / cols.length)));
    for (let off = 0; off < total; off += batch) {
      if (isCancelled()) throw new Error("Stopped.");
      const rows = (await src.query(`select ${names} from ${q(t)} order by ctid limit ${batch} offset ${off}`)).rows;
      if (!rows.length) break;
      const params = [];
      const tuples = rows.map((row) => {
        const ph = cols.map((c, i) => { let v = row[c.column_name]; if (v !== null && isJson[i]) v = JSON.stringify(v); params.push(v); return "$" + params.length; });
        return "(" + ph.join(", ") + ")";
      });
      await dst.query(`insert into ${q(t)} (${names}) ${hasIdentityAlways ? "overriding system value " : ""}values ${tuples.join(", ")} on conflict do nothing`, params);
    }
    const after = Number((await dst.query(`select count(*) from ${q(t)}`)).rows[0].count);
    totalInserted += after - before;
    log(`${t}: source ${total}, destination ${before} -> ${after} (+${after - before})`);
  }
  if (apply) {
    const seqs = await dst.query(
      `select c.relname as t, a.attname as col, pg_get_serial_sequence(format('%I.%I', n.nspname, c.relname), a.attname) as seq
       from pg_class c join pg_namespace n on n.oid = c.relnamespace
       join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
       where c.relkind='r' and n.nspname='public' and pg_get_serial_sequence(format('%I.%I', n.nspname, c.relname), a.attname) is not null`);
    for (const { t, col, seq } of seqs.rows)
      await dst.query(`select setval($1, coalesce((select max(${q(col)}) from ${q(t)}), 1), (select count(*) > 0 from ${q(t)}))`, [seq]);
    log(`Sequences reset: ${seqs.rowCount}. Total new rows inserted: ${totalInserted}`);
  }
  return { inserted: totalInserted };
}

/* ---------- jobs ---------- */
const STEPS = {
  schema: "1. Copy structure",
  dry: "2. Check (dry run)",
  copy: "3. Copy data",
  finish: "4. Finish (keys and indexes)",
  all: "Full transfer (1 to 4)"
};

function publicJob() {
  if (!job) return { running: false, job: null, env: envUrls() };
  return {
    running: job.running, env: envUrls(),
    job: { id: job.id, step: job.step, label: STEPS[job.step], from: job.from, to: job.to, started: job.started, ended: job.ended, ok: job.ok, error: job.error, log: job.log.slice(-600), lines: job.log.length }
  };
}

function start({ src, dst, step, by }) {
  if (job && job.running) throw new Error("A transfer is already running. Wait for it to finish.");
  if (!STEPS[step]) throw new Error("Unknown step.");
  const S = cleanUrl(src || process.env.SRC_URL), D = cleanUrl(dst || process.env.DST_URL);
  if (S === D || hostOf(S) + new URL(S).pathname === hostOf(D) + new URL(D).pathname) throw new Error("Source and destination are the same database.");
  const urls = [S, D];
  const me = { id: Date.now().toString(36), step, from: hostOf(S), to: hostOf(D), started: new Date().toISOString(), ended: null, running: true, ok: null, error: null, log: [], cancel: false };
  job = me;
  const log = (m) => { me.log.push(scrub(m, urls)); if (me.log.length > MAX_LOG) me.log.splice(0, me.log.length - MAX_LOG); };
  console.warn(`[DB TRANSFER] ${STEPS[step]} started by ${by || "admin"}: ${me.from} -> ${me.to}`);
  (async () => {
    const s = new Client({ connectionString: S, connectionTimeoutMillis: 30000 });
    const d = new Client({ connectionString: D, connectionTimeoutMillis: 30000 });
    s.on("error", () => {}); d.on("error", () => {});
    try {
      await s.connect(); await d.connect();
      log(`Reading from ${me.from} -> writing to ${me.to}`);
      const cancelled = () => me.cancel;
      const steps = step === "all" ? ["schema", "copy", "finish"] : [step];
      for (const st of steps) {
        if (steps.length > 1) log(`--- ${STEPS[st]} ---`);
        if (st === "schema") await schemaStep(s, d, false, log);
        else if (st === "finish") await schemaStep(s, d, true, log);
        else await rowsStep(s, d, st === "copy", log, cancelled);
      }
      me.ok = true; log("FINISHED OK.");
    } catch (e) {
      me.ok = false; me.error = scrub(e.message, urls); log("FAILED: " + me.error);
    } finally {
      me.running = false; me.ended = new Date().toISOString();
      try { await s.end(); } catch (e) {} try { await d.end(); } catch (e) {}
      console.warn(`[DB TRANSFER] ${STEPS[step]} ${me.ok ? "finished" : "failed"}`);
    }
  })();
  return publicJob();
}
function stop() { if (job && job.running) { job.cancel = true; } return publicJob(); }

module.exports = { start, stop, status: publicJob, STEPS };
