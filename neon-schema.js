// Copies table structure (not rows) from SRC_URL to DST_URL.
//   node neon-schema.js          -> extensions, types, sequences, tables, PK/unique/check constraints
//   node neon-schema.js --post   -> foreign keys and indexes (run AFTER the data copy)
const { Client } = require('pg');
const POST = process.argv.includes('--post');
const SRC = process.env.SRC_URL, DST = process.env.DST_URL;
if (!SRC || !DST || SRC === DST) { console.error('Set SRC_URL and DST_URL (different values).'); process.exit(1); }
const q = (s) => '"' + String(s).replace(/"/g, '""') + '"';
const lit = (s) => "'" + String(s).replace(/'/g, "''") + "'";

(async () => {
  const s = new Client({ connectionString: SRC });
  const d = new Client({ connectionString: DST });
  await s.connect(); await d.connect();
  console.log('Reading from', new URL(SRC).host, '-> writing to', new URL(DST).host);
  let ok = 0, warn = 0;
  const run = async (sql) => {
    try { await d.query(sql); ok++; }
    catch (e) {
      if (/already exists|multiple primary keys/i.test(e.message)) return;
      warn++; console.log('WARN:', e.message, '\n     ', sql.slice(0, 140));
    }
  };

  if (!POST) {
    for (const r of (await s.query(`select extname::text e from pg_extension where extname <> 'plpgsql'`)).rows)
      await run(`create extension if not exists ${q(r.e)}`);

    const enums = await s.query(
      `select t.typname::text n, array_agg(e.enumlabel::text order by e.enumsortorder) labels
       from pg_type t join pg_enum e on e.enumtypid = t.oid
       join pg_namespace n on n.oid = t.typnamespace where n.nspname = 'public' group by t.typname`);
    for (const r of enums.rows)
      await run(`create type public.${q(r.n)} as enum (${r.labels.map(lit).join(', ')})`);

    const seqs = await s.query(
      `select c.relname::text n, format_type(q.seqtypid, null) typ, q.seqstart st, q.seqincrement inc,
              q.seqmin mn, q.seqmax mx, q.seqcache ca, q.seqcycle cy
       from pg_sequence q join pg_class c on c.oid = q.seqrelid
       join pg_namespace n on n.oid = c.relnamespace
       where n.nspname = 'public'
         and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')`);
    for (const r of seqs.rows)
      await run(`create sequence if not exists public.${q(r.n)} as ${r.typ} increment by ${r.inc} minvalue ${r.mn} maxvalue ${r.mx} start ${r.st} cache ${r.ca} ${r.cy ? 'cycle' : 'no cycle'}`);

    const cols = await s.query(
      `select c.relname::text t, a.attname::text col, format_type(a.atttypid, a.atttypmod) typ,
              a.attnotnull nn, a.attidentity::text ident, a.attgenerated::text gen,
              pg_get_expr(ad.adbin, ad.adrelid) def
       from pg_attribute a join pg_class c on c.oid = a.attrelid
       join pg_namespace n on n.oid = c.relnamespace
       left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
       where n.nspname = 'public' and c.relkind = 'r' and a.attnum > 0 and not a.attisdropped
       order by c.relname, a.attnum`);
    const byTable = new Map();
    for (const r of cols.rows) { if (!byTable.has(r.t)) byTable.set(r.t, []); byTable.get(r.t).push(r); }
    for (const [t, cs] of byTable) {
      const defs = cs.map((c) => {
        let x = `${q(c.col)} ${c.typ}`;
        if (c.ident === 'a') x += ' generated always as identity';
        else if (c.ident === 'd') x += ' generated by default as identity';
        else if (c.gen === 's') x += ` generated always as (${c.def}) stored`;
        else if (c.def) x += ` default ${c.def}`;
        if (c.nn && !c.ident) x += ' not null';
        return x;
      });
      await run(`create table if not exists public.${q(t)} (${defs.join(', ')})`);
      console.log('table', t);
    }

    const cons = await s.query(
      `select k.conname::text name, r.relname::text t, pg_get_constraintdef(k.oid) def
       from pg_constraint k join pg_class r on r.oid = k.conrelid
       join pg_namespace n on n.oid = r.relnamespace
       where n.nspname = 'public' and k.contype in ('p','u','c','x') order by r.relname`);
    for (const r of cons.rows)
      await run(`alter table public.${q(r.t)} add constraint ${q(r.name)} ${r.def}`);

    const own = await s.query(
      `select sq.relname::text seq, t.relname::text tbl, a.attname::text col
       from pg_depend d join pg_class sq on sq.oid = d.objid and sq.relkind = 'S'
       join pg_class t on t.oid = d.refobjid
       join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid
       join pg_namespace n on n.oid = sq.relnamespace
       where d.deptype = 'a' and n.nspname = 'public'`);
    for (const r of own.rows)
      await run(`alter sequence public.${q(r.seq)} owned by public.${q(r.tbl)}.${q(r.col)}`);
  } else {
    const fks = await s.query(
      `select k.conname::text name, r.relname::text t, pg_get_constraintdef(k.oid) def
       from pg_constraint k join pg_class r on r.oid = k.conrelid
       join pg_namespace n on n.oid = r.relnamespace
       where n.nspname = 'public' and k.contype = 'f' order by r.relname`);
    for (const r of fks.rows)
      await run(`alter table public.${q(r.t)} add constraint ${q(r.name)} ${r.def}`);

    const idx = await s.query(
      `select pg_get_indexdef(i.indexrelid) def
       from pg_index i join pg_class c on c.oid = i.indrelid
       join pg_namespace n on n.oid = c.relnamespace
       where n.nspname = 'public' and c.relkind = 'r'
         and not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid)`);
    for (const r of idx.rows)
      await run(r.def.replace(/^CREATE (UNIQUE )?INDEX /i, 'CREATE $1INDEX IF NOT EXISTS '));
  }
  console.log(`Done. ${ok} statements applied, ${warn} warnings.`);
  await s.end(); await d.end();
})().catch((e) => { console.error('FAILED:', e.message); process.exit(1); });